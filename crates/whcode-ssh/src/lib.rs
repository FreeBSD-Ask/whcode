//! # whcode-ssh
//!
//! SSH 入口：公钥认证、会话隔离、终端尺寸变化与安全退出（FR-607/608、ADR-005）。
//!
//! **当前状态：仅客户端风险原型已交付，服务端未实现。**
//!
//! 平台承诺已修订：OpenBSD 与 DragonFly 不再作为原生安装目标，改由 WHCode 内置 SSH
//! **客户端**控制。因此 M0 的风险原型（tasks.md T025）只实现从 WHCode 向远端发起命令的
//! **客户端路径**：[`proto::run_command`] 按 ADR-007 的“意图记录—执行—结果登记”协议执行
//! 命令，并把结果交给 [`proto::ExecRegistry`] 登记。
//!
//! 本 crate 的**服务端**（原生监听、公钥认证分发、终端尺寸、受限入口）属 M7
//! （tasks.md T096—T099），**尚未实现**；四 BSD 的 SSH 验收（V-004）**未取得证据**。
//!
//! 硬约束（ADR-005）：SSH 是独立传输入口，**复用**应用服务，不得每会话各自打开数据库并
//! 直接写入；默认只开放受限 WHCode 交互入口，任意系统 Shell 是显式独立权限（FR-608）。

